"""Evaluate a public labeled video without treating interval midpoints as impact.

Uses fresh YOLO output or a hash-recorded cached output generated by our worker.
Both sparse detections and oracle-boundary classification are reported separately.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from pipeline.boxing_research import (LABELS, digest, read_labels, pose_features,
    classification_metrics, evaluate_intervals, softmax)
from train_boxing_research import COMMIT, DATA_DEFAULT, REPO, load_research_model, predict_logits


def classify_interval(frames, start, end, model, card):
    selected = [frames.get(index) for index in range(start, end + 1)]
    if any(frame is None or frame.get("observationKind") != "fresh_detection"
           or frame.get("isDiscontinuous") for frame in selected):
        return {"technique": "unknown", "reason": "MISSING_OR_DISCONTINUOUS_POSE", "confidence": None}
    clip = np.zeros((len(selected), 17, 2), dtype=np.float32)
    for i, frame in enumerate(selected):
        landmarks = frame.get("landmarks", [])
        if len(landmarks) != 17:
            return {"technique": "unknown", "reason": "MISSING_POSE", "confidence": None}
        for j, point in enumerate(landmarks):
            if point.get("conf", 0) >= .3:
                clip[i, j] = point["x"], point["y"]
    try:
        features = pose_features(clip)
    except ValueError as error:
        return {"technique": "unknown", "reason": str(error), "confidence": None}
    probabilities = softmax(predict_logits(model, features[None]), card["temperature"])[0]
    candidate = LABELS[int(probabilities.argmax())]
    return {"technique": candidate if probabilities.max() >= .8 else "unknown",
            "candidate": candidate, "researchSoftmax": float(probabilities.max()), "confidence": None,
            "reason": "RESEARCH_ONLY_ACCEPTED_AT_FIXED_THRESHOLD" if probabilities.max() >= .8 else "LOW_RESEARCH_PROBABILITY"}


def evaluate(data: Path, result_path: Path, model_directory: Path | None = None):
    document = json.loads(result_path.read_text(encoding="utf-8"))
    truth = read_labels(data / "adam_gt.csv")
    frame_map = {f["frameIdx"]: f for f in document["frames"]}
    if len(frame_map) != len(document["frames"]) or not frame_map:
        raise ValueError("Invalid or duplicate prediction frame indices")
    if any(row["endFrame"] > max(frame_map) for row in truth):
        raise ValueError("Inference did not reach all annotated intervals")
    # Upstream evaluation indexes zero-based inclusive frames. Keep convention;
    # shared endpoints remain shared, never rewrite source ground truth.
    baseline = [{"startFrame": p["startFrame"], "endFrame": p["endFrame"],
                 "technique": p.get("punchType", "unknown").strip().lower().replace(" ", "_")}
                for p in document.get("punches", [])]
    shadow = document.get("shadowEventDetection", {}).get("events", [])
    pools = {"legacy": baseline, "shadow": shadow}
    report = {"schemaVersion": "1.0.0", "purpose": "external_diagnostic_not_production_acceptance",
              "source": {"repository": REPO, "commit": COMMIT, "video": "videos/adam.mp4", "annotation": "evaluation/adam_gt.csv"},
              "inputHashes": {"video": digest(data / "adam.mp4"), "annotation": digest(data / "adam_gt.csv"), "inference": digest(result_path)},
              "poseModelSha256": digest(Path("yolov8n-pose.pt")),
              "evaluationRuntimeHashes": {p: digest(Path(p)) for p in ("process_video.py", "pipeline/strike_events.py", "pipeline/boxing_research.py", "evaluate_external_boxing.py")},
              "cachedInferenceRuntimeVerified": False,
              "frameConvention": "zero_based_inclusive_upstream_evaluator", "annotationCount": len(truth),
              "fps": document["meta"]["fps"], "processedFrames": len(frame_map),
              "lastProcessedFrame": max(frame_map), "groundTruth": truth,
              "productionEligible": False,
              "limitations": ["One external video, not representative of athlete/camera population.",
                "Annotations are upstream single-source labels, not independently coach-adjudicated here.",
                "Unmatched predictions count as false positives under assumed exhaustive annotation; exhaustiveness is unverified.",
                "Temporal IoU is not impact-timing accuracy. Source has no impact or technique-quality labels.",
                "Commercial media and upstream data rights remain unverified.",
                "Research classifier has AlphaPose-to-YOLO pose-source and image-aspect domain shift."]}
    if model_directory is not None:
        model, card = load_research_model(model_directory)
        report["researchModel"] = card
        oracle_predictions = [classify_interval(frame_map, row["startFrame"], row["endFrame"], model, card) for row in truth]
        report["oracleBoundaryClassifier"] = {
            "allCandidates": classification_metrics([row["technique"] for row in truth], [p.get("candidate", "unknown") for p in oracle_predictions]),
            "withAbstention": classification_metrics([row["technique"] for row in truth], [p["technique"] for p in oracle_predictions]),
            "predictions": oracle_predictions,
            "note": "Uses ground-truth intervals: classification diagnostic only, not end-to-end accuracy."}
        for name, events in list(pools.items()):
            pools[name + "_research_classifier"] = [dict(event, **classify_interval(
                frame_map, event["startFrame"], event["endFrame"], model, card)) for event in events]
    report["detectors"] = {name: {"predictionCount": len(events), "predictions": events,
        "byIoU": {str(iou): evaluate_intervals(truth, events, iou) for iou in (.1, .3, .5)}} for name, events in pools.items()}
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DATA_DEFAULT)
    parser.add_argument("--inference", type=Path, default=Path("test_results/external/adam_fresh_baseline.json"))
    parser.add_argument("--model", type=Path)
    parser.add_argument("--output", type=Path, default=Path("benchmark_results/external_adam_report.json"))
    parser.add_argument("--fresh", action="store_true")
    args = parser.parse_args()
    if args.fresh:
        from process_video import process_video
        process_video(str(args.data / "adam.mp4"), output_path=str(args.inference), training_mode="SHADOW_BOXING", verbose=False)
    result = evaluate(args.data, args.inference, args.model)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps({name: {k: v for k, v in item["byIoU"]["0.1"].items() if k in ("tp", "fp", "fn", "precision", "recall", "f1")}
                      for name, item in result["detectors"].items()}))

"""
pipeline/shadow_classifier.py — Task 8 Stance-Aware Shadow Jab-Cross Classifier MVP

Module implementing shadow classification for straight punches (jab/cross)
using stance context and action-window kinematic features.

Key Design Principles:
1. Shadow Mode Isolation:
   - Does NOT mutate existing legacy detector outputs or ActionResult public properties.
   - Outputs ClassificationDecision serializable to dict matching Zod shadowClassificationSchema.
2. Canonical Data Contracts:
   - Canonical EvidenceLevel imported from pipeline.contracts
   - DecisionStatus (CLASSIFIED, ABSTAINED, REJECTED_CANDIDATE)
   - TechniqueCandidate (technique, family, attacking_side, limb_role, stance)
   - ClassifierProvenance (classifier_id, classifier_version, config_version, feature_version, stance_source)
   - ShadowClassifierConfig (thresholds for elbow extension, directness, curvature, reach)
   - ClassificationDecision (to_dict parity with frontend schema)
3. Guardrails:
   - Case A: Missing or unsupported evidence -> ABSTAINED, evidenceLevel="unavailable", reasonCodes=["INSUFFICIENT_EVIDENCE"].
   - Case B: Unresolved stance/limb -> ABSTAINED, evidenceLevel="derived_proxy", reasonCodes=["UNRESOLVED_STANCE_OR_LIMB"].
   - Case C: Curved punch / low extension -> REJECTED_CANDIDATE, reasonCodes=["CURVED_TRAJECTORY_REJECTED"] / ["INSUFFICIENT_EXTENSION_OR_REACH"].
   - Case D: Nominal straight punch -> CLASSIFIED, lead=jab, rear=cross, confidence=None, evidenceLevel="derived_proxy".
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from enum import Enum
import math
from typing import Any, Optional, Union

from pipeline.contracts import EvidenceLevel
from pipeline.stance_context import (
    StanceContext,
    StanceType,
    normalize_attacking_side,
    resolve_limb_role,
)

__all__ = [
    "EvidenceLevel",
    "DecisionStatus",
    "TechniqueCandidate",
    "ClassifierProvenance",
    "ShadowClassifierConfig",
    "ClassificationDecision",
    "ShadowClassifier",
    "classify_shadow_punch",
]


# ===========================================================================
# Canonical Enums & Data Contracts
# ===========================================================================

class DecisionStatus(str, Enum):
    CLASSIFIED = "classified"
    ABSTAINED = "abstained"
    REJECTED_CANDIDATE = "rejected_candidate"


@dataclass(frozen=True)
class TechniqueCandidate:
    """Candidate prediction generated by the shadow classifier."""
    technique: str        # e.g. "jab", "cross"
    family: str = "punch" # "punch" | "kick" | "other_strike" | "non_strike"
    attacking_side: str = "unknown"   # "left" | "right" | "unknown"
    limb_role: str = "unknown"        # "lead" | "rear" | "unknown"
    stance: str = "unknown"           # "orthodox" | "southpaw" | "switch" | "unknown"


@dataclass(frozen=True)
class ClassifierProvenance:
    """Provenance tracking classifier ID, version, config, and stance source."""
    classifier_id: str = "shadow_jab_cross_classifier"
    classifier_version: str = "1.0.0"
    config_version: str = "1.0.0"
    feature_version: str = "1.0.0"
    stance_source: str = "stance_context"


@dataclass(frozen=True)
class ShadowClassifierConfig:
    """Configurable thresholds for geometric & kinematic straight punch gating."""
    config_version: str = "1.0.0"
    min_elbow_extension_deg: float = 140.0
    min_trajectory_directness: float = 0.82
    max_tangential_curvature: float = 0.20
    min_reach_ratio: float = 0.70


@dataclass(frozen=True)
class ClassificationDecision:
    """
    Result of shadow classification with field-for-field parity to
    frontend Zod shadowClassificationSchema.
    """
    status: DecisionStatus
    candidate: Optional[TechniqueCandidate]
    reason_codes: tuple[str, ...]
    provenance: ClassifierProvenance
    confidence: Optional[float] = None
    evidence_level: EvidenceLevel = EvidenceLevel.DERIVED_PROXY

    def to_dict(self) -> dict[str, Any]:
        """Convert decision to dict matching frontend shadowClassificationSchema."""
        return {
            "status": self.status.value,
            "candidate": {
                "technique": self.candidate.technique,
                "family": self.candidate.family,
                "attackingSide": self.candidate.attacking_side,
                "limbRole": self.candidate.limb_role,
                "stance": self.candidate.stance,
            } if self.candidate is not None else None,
            "confidence": self.confidence,
            "reasonCodes": list(self.reason_codes),
            "classifierId": self.provenance.classifier_id,
            "classifierVersion": self.provenance.classifier_version,
            "configVersion": self.provenance.config_version,
            "featureVersion": self.provenance.feature_version,
            "stanceSource": self.provenance.stance_source,
            "evidenceLevel": self.evidence_level.value,
        }


